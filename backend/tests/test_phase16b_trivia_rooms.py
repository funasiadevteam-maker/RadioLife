# ─── 1. Code entropy / no ambiguity ─────────────────────────────────────
def test_create_room_returns_unambiguous_code():
    from services.trivia_rooms import generate_room_code, ROOM_CODE_PREFIX
    seen = set()
    for _ in range(1000):
        code = generate_room_code()
        assert code.startswith(ROOM_CODE_PREFIX)
        body = code[len(ROOM_CODE_PREFIX):]
        assert len(body) == 6
        # Every body char must be in the unambiguous alphabet.
        for ch in body:
            assert ch in ALLOWED_CODE_CHARS, (
                f"ambiguous char {ch!r} leaked into {code}")
            assert ch not in "0O1Il"
        seen.add(code)
    # 31**6 ≈ 887M possibilities, no duplicates in 1000 draws.
    assert len(seen) == 1000


# ─── helper: spin up a fresh room owned by the demo user ─────────────
def _create_room(session) -> tuple[str, dict]:
    # Trigger category seed via /categories first.
    session.get("/trivia/categories")
    r = session.post("/trivia/rooms",
                          json={"category_id": "global-music", "is_private": False})
    assert r.status_code == 200, r.text
    body = r.json()
    return body["room_code"], body


# ─── 2. Join in lobby phase succeeds ────────────────────────────────────
def test_join_room_in_lobby_phase_succeeds(session: httpx.Client):
    code, _ = _create_room(session)
    # Second user — fresh demo session (auto-creates a second user
    # because /auth/demo upserts by email and there's only one demo
    # account, so it's the same user re-joining → returns 200 with
    # current state).
