# ─── 12. Start with <2 players returns a structured 400 ───────────────
def test_start_with_one_player_returns_structured_error():
    """The host shouldn't see a generic 'Failed to start' toast — the
    server's reply must carry an explicit reason the UI can render.
    We test against the live preview server (TestClient skips the
    backend's async startup bootstrap that seeds trivia categories)."""
    import httpx
    base = "http://localhost:8001"
    with httpx.Client(base_url=base, timeout=10) as client:
        r = client.post("/api/auth/demo")
        assert r.status_code == 200, r.text
        # The auth cookie is `Secure; SameSite=none` so httpx via http://
        # won't store it.  Pull it manually and inject it for the rest
        # of the test.
        raw = r.headers.get("set-cookie", "")
        token = raw.split("bigfm_session=", 1)[1].split(";", 1)[0]
        assert token, raw
        client.cookies.set("bigfm_session", token)
        cats = client.get("/api/trivia/categories").json().get("categories", [])
        assert cats, "no trivia categories seeded on live server"
        cat = cats[0]["id"]
        r = client.post("/api/trivia/rooms", json={"category_id": cat, "is_private": False})
        assert r.status_code == 200, r.text
        code = r.json()["room_code"]
        try:
            # Host is the only player.  Start must fail with structured detail.
            r = client.post(f"/api/trivia/rooms/{code}/start")
            assert r.status_code == 400, r.text
            d = r.json().get("detail")
            assert isinstance(d, dict), r.text
            assert d["code"]     == "need_more_players"
            assert d["required"] == 2
            assert d["current"]  == 1
            assert "Need at least 2 players" in d["message"]
        finally:
            # Cleanup: host leaves so the room disappears.
            client.post(f"/api/trivia/rooms/{code}/leave")


# ─── 13. Joining via REST broadcasts player_joined over WS ────────────
def test_join_broadcasts_player_joined_to_existing_members():
    """Witness assertion: when Player B joins via REST, Player A's WS
    must receive a `player_joined` frame within the same event-loop turn."""
    asyncio.set_event_loop(asyncio.new_event_loop())
    loop = asyncio.get_event_loop()
    from services.trivia_rooms import RoomHub

    class FakeWS:
        def __init__(self):
            self.sent = []
            self.closed_with = None
        async def send_text(self, p):
            self.sent.append(p)
        async def close(self, code=1000, reason=""):
            self.closed_with = (code, reason)

    async def run():
        hub = RoomHub()
        room = await hub.create(host_user={"user_id": "u_a", "name": "A"},
                                       category_id="x", category_slug="x", market="dubai")
