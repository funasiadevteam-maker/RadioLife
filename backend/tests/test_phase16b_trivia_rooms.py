# ─── 9. Kicked player receives `kicked` event + WS closed with 4001 ───
def test_kicked_player_receives_kicked_event_and_socket_closes():
    """Host kicks a player → victim's WS gets a targeted `{type:"kicked"}`
    frame AND is server-closed with code 4001 BEFORE the player_left
    broadcast.  Regression test for the silent-kick bug (16b tester
    verdict 3/4)."""
    asyncio.set_event_loop(asyncio.new_event_loop())
    loop = asyncio.get_event_loop()
    from services.trivia_rooms import RoomHub

    class FakeWS:
        def __init__(self):
            self.sent: list[str] = []
            self.closed_with = None
        async def send_text(self, payload):
            self.sent.append(payload)
        async def close(self, code: int = 1000, reason: str = ""):
            self.closed_with = (code, reason)

    async def run():
        hub = RoomHub()
        room = await hub.create(host_user={"user_id": "u_host", "name": "Host"},
                                       category_id="x", category_slug="x", market="dubai")
        # Host auto-joined; add the victim + a witness.
        await hub.add_player(room.code, {"user_id": "u_victim",  "name": "Victim"})
        await hub.add_player(room.code, {"user_id": "u_witness", "name": "Witness"})
        host_ws, victim_ws, witness_ws = FakeWS(), FakeWS(), FakeWS()
        hub.attach_socket(room.code, "u_host",    host_ws)
        hub.attach_socket(room.code, "u_victim",  victim_ws)
        hub.attach_socket(room.code, "u_witness", witness_ws)

        # The kick.
        was_member = await hub.kick(room.code, "u_victim")
        assert was_member is True

        # 1. Victim gets the targeted `kicked` frame.
        kicked_msgs = [json.loads(p) for p in victim_ws.sent
                            if '"kicked"' in p and '"type"' in p]
        assert len(kicked_msgs) == 1, victim_ws.sent
        k = kicked_msgs[0]
        assert k["type"]       == "kicked"
        assert k["reason"]    == "removed_by_host"
        assert k["room_code"] == room.code
        assert isinstance(k["kicked_at"], int)

        # 2. Victim's WS server-closed with code 4001.
        assert victim_ws.closed_with is not None, "victim ws was not closed"
        assert victim_ws.closed_with[0] == 4001
        assert "kick" in victim_ws.closed_with[1].lower()

        # 3. Victim removed from the room dict.
        assert "u_victim" not in hub.get(room.code).players

        # 4. Remaining members get a `player_left` broadcast with reason
        # "kicked".  Host + witness sockets each receive exactly one.
        for ws in (host_ws, witness_ws):
            left_msgs = [json.loads(p) for p in ws.sent
                              if '"player_left"' in p]
            assert len(left_msgs) == 1, ws.sent
            assert left_msgs[0]["user_id"] == "u_victim"
            assert left_msgs[0]["reason"]  == "kicked"

        # 5. Idempotent kick on a now-non-member is a no-op + returns False.
        was_member2 = await hub.kick(room.code, "u_victim")
        assert was_member2 is False

    loop.run_until_complete(run())


# ─── 10. Code normalization (case + prefix + hyphen + whitespace) ─────
def test_normalize_room_code_accepts_variants():
    """User report: Window A joined with the wrong-cased / un-hyphenated
    code and got 'room not found'.  All of these variants must collapse
    to the same canonical key."""
    from routes.trivia_room_routes import normalize_room_code
    canon = "BFM-9U32KK"
    variants = [
        "BFM-9U32KK",
        "bfm-9u32kk",
        "BFM9U32KK",      # no hyphen
        "bfm9u32kk",      # no hyphen, lower
        "9U32KK",          # body only
        "9u32kk",          # body only, lower
        "  BFM-9U32KK  ", # surrounding whitespace
        " bfm 9u32kk ",   # internal space + lower
        "BFM-9U32-KK",    # extra internal hyphen
    ]
    for v in variants:
        assert normalize_room_code(v) == canon, f"{v!r} → {normalize_room_code(v)!r}"


# ─── 11. join + snapshot lookups respect normalization ────────────────
def test_join_accepts_code_with_and_without_prefix_and_case():
    """All 4 join input variants must resolve to the same room."""
    asyncio.set_event_loop(asyncio.new_event_loop())
