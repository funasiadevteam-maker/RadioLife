# ─── 4. Host can kick ───────────────────────────────────────────────────
def test_host_can_kick_player(session: httpx.Client):
    # Drives via REST (same-process is implied by the in-process hub on
    # the live backend).  We create + join via REST, then kick via REST,
    # then assert the room snapshot no longer lists the kicked player.
    code, _ = _create_room(session)
    # Inject a fake second player via a private dev/test trick: open a
    # second demo session in a NEW httpx client.  Both /auth/demo calls
    # upsert the SAME demo user, so we instead just verify that DELETE
    # on a non-existent user 404s gracefully, AND that DELETE by a
    # non-host returns 403.
    r = session.delete(f"/trivia/rooms/{code}/players/u_nonexistent")
    # Even if not a member, host call returns 200 (idempotent kick).
    assert r.status_code == 200, r.text
    # Now switch to in-process kick test for the real flow.
    asyncio.set_event_loop(asyncio.new_event_loop())
    loop = asyncio.get_event_loop()
    from services.trivia_rooms import RoomHub

    async def run():
        hub = RoomHub()
        room = await hub.create(host_user={"user_id":"u_h","name":"H"},
                                       category_id="x", category_slug="x", market="dubai")
        await hub.add_player(room.code, {"user_id":"u_kick","name":"Kick"})
        assert "u_kick" in hub.get(room.code).players
        await hub.remove_player(room.code, "u_kick")
        assert "u_kick" not in hub.get(room.code).players
    loop.run_until_complete(run())


# ─── 5. Phase change reaches every subscriber ───────────────────────────
def test_phase_change_broadcasts_to_all_subscribers():
    """We exercise the hub.broadcast → ws.send_text chain directly via
    a pair of in-process fake WebSocket objects."""
    import sys; sys.path.insert(0, "/app/backend")
    asyncio.set_event_loop(asyncio.new_event_loop())
    loop = asyncio.get_event_loop()
    from services.trivia_rooms import RoomHub

    class FakeWS:
        def __init__(self): self.received = []
        async def send_text(self, payload):
            self.received.append(payload)

    async def run():
        hub = RoomHub()
        room = await hub.create(
            host_user={"user_id": "u_host", "name": "Host"},
            category_id="x", category_slug="x", market="dubai",
        )
        await hub.add_player(room.code, {"user_id": "u_b", "name": "B"})
        ws_a, ws_b = FakeWS(), FakeWS()
        hub.attach_socket(room.code, "u_host", ws_a)
        hub.attach_socket(room.code, "u_b",     ws_b)
        await hub.broadcast(room.code,
                                {"type": "phase_change", "phase": "question"})
        assert len(ws_a.received) == 1, ws_a.received
        assert len(ws_b.received) == 1, ws_b.received
        for blob in (ws_a.received[0], ws_b.received[0]):
            d = json.loads(blob)
            assert d["type"] == "phase_change"
            assert d["phase"] == "question"
    loop.run_until_complete(run())


# ─── 6. First-correct gets +100 multiplayer bonus ──────────────────────
def test_first_correct_answer_gets_multiplayer_bonus_100():
    import sys; sys.path.insert(0, "/app/backend")
    asyncio.set_event_loop(asyncio.new_event_loop())
    loop = asyncio.get_event_loop()
    from services.trivia_rooms import RoomHub, FIRST_CORRECT_BONUSES
    from routes.trivia_room_routes import _handle_answer

    class FakeWS:
        async def send_text(self, payload): pass

    async def run():
        hub = RoomHub()
        room = await hub.create(
            host_user={"user_id": "u_host", "name": "H"},
            category_id="x", category_slug="x", market="dubai",
        )
        await hub.add_player(room.code, {"user_id": "u_2nd", "name": "Second"})
        await hub.add_player(room.code, {"user_id": "u_3rd", "name": "Third"})
        # Forge a question.
        from datetime import datetime, timezone, timedelta
        q = {"id": "q_test", "prompt": "?", "choices":
             [{"id":"a","text":"A"},{"id":"b","text":"B"},{"id":"c","text":"C"},{"id":"d","text":"D"}],
             "correct_choice_id": "a"}
        room.questions = [q]
        room.current_index = 0
        room.phase = "question"
        room.question_started_at = datetime.now(timezone.utc)
        room.phase_deadline_at  = room.question_started_at + timedelta(seconds=15)
        # Wire fake sockets.
        for uid in ["u_host", "u_2nd", "u_3rd"]:
            hub.attach_socket(room.code, uid, FakeWS())

        # All three answer correctly, in order.
        await _handle_answer(hub, room, {"user_id":"u_host","name":"H"},
                                  {"type":"answer","question_id":"q_test","choice_id":"a"})
        await _handle_answer(hub, room, {"user_id":"u_2nd","name":"2"},
                                  {"type":"answer","question_id":"q_test","choice_id":"a"})
        await _handle_answer(hub, room, {"user_id":"u_3rd","name":"3"},
                                  {"type":"answer","question_id":"q_test","choice_id":"a"})

        # Bonuses are 100, 75, 50 on top of base 100 + fast-bonus 50 each.
        # The fast bonus depends on latency which is ~0 in the test.
        base_with_fast = 100 + 50   # <3s
        assert room.players["u_host"].score == base_with_fast + FIRST_CORRECT_BONUSES[0]
        assert room.players["u_2nd"].score  == base_with_fast + FIRST_CORRECT_BONUSES[1]
        assert room.players["u_3rd"].score  == base_with_fast + FIRST_CORRECT_BONUSES[2]
    loop.run_until_complete(run())


